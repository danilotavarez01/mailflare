// Endpoints in the formats of addy.io and SimpleLogin, so password managers
// that support those services (Bitwarden, for one) can create Mailflare
// aliases. Point them at a self-hosted server:
//
//   addy.io:     https://<worker>/api/addy         (Authorization: Bearer <key>)
//   SimpleLogin: https://<worker>/api/simplelogin  (Authentication: <key>)
//
// The keys (api_keys) only create aliases, each with the destination and
// address format chosen for the key.

import { eq } from "drizzle-orm";
import { type Context, Hono } from "hono";
import type { ContentfulStatusCode } from "hono/utils/http-status";

import { generateAliasAddress, type GenerateAliasOptions } from "../alias-address";
import { createDb, type Db, schema } from "../db";
import { ApiException, type Caller, createAlias, isAdmin } from "./common";

const KEY_PREFIX = "mf_";

async function sha256Hex(text: string) {
    const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(text));
    return [...new Uint8Array(digest)].map((b) => b.toString(16).padStart(2, "0")).join("");
}

/** A new key and what is stored of it. */
export async function newApiKey() {
    const bytes = crypto.getRandomValues(new Uint8Array(32));
    const base64url = btoa(String.fromCharCode(...bytes))
        .replace(/\+/g, "-")
        .replace(/\//g, "_")
        .replace(/=+$/, "");
    const key = KEY_PREFIX + base64url;
    return { key, keyHash: await sha256Hex(key), start: key.slice(0, KEY_PREFIX.length + 4) };
}

/** The key's row and whose rights it carries; 401 for unknown keys. */
async function authenticate(db: Db, key: string) {
    const unauthorized = new ApiException(401, "unauthorized", "Invalid API key");
    if (!key.startsWith(KEY_PREFIX)) throw unauthorized;
    const row = await db.query.apiKeys.findFirst({
        where: { keyHash: await sha256Hex(key) },
        with: { destination: true, domain: true, user: true },
    });
    if (!row) throw unauthorized;
    if (row.user?.banned) throw new ApiException(403, "banned", "This account is suspended");
    const caller: Caller = row.user ? { kind: "user", user: row.user } : { kind: "token" };
    return { key: row, caller };
}

/** The first hostname in text, such as Bitwarden's "Website: example.com. Generated by Bitwarden." */
export function hostnameIn(text: string): string | undefined {
    return /(?:^|[\s(:/])((?:[a-z0-9](?:[a-z0-9-]*[a-z0-9])?\.)+[a-z]{2,63})(?=$|[\s).,:/])/i
        .exec(text)?.[1]
        ?.toLowerCase();
}

const ATTEMPTS = 5;

/**
 * Creates an alias with the key's settings. Generated addresses can be taken,
 * so it tries a few; a "domain" format address gets random characters added.
 */
async function createForKey(
    env: Env,
    db: Db,
    auth: Awaited<ReturnType<typeof authenticate>>,
    request: { domain?: string; description: string; hostname?: string },
) {
    const { key, caller } = auth;
    const domain = await chooseDomain(db, caller, key.domain, request.domain);
    if (!key.destination.verifiedAt) {
        throw new ApiException(
            400,
            "unverified_destination",
            `${key.destination.email} isn't confirmed`,
        );
    }
    const options: GenerateAliasOptions = { ...key.format, hostname: request.hostname };
    // Without a website, there's nothing to name the alias after.
    if (options.format === "domain" && !request.hostname) options.format = "characters";
    for (let attempt = 0; attempt < ATTEMPTS; attempt += 1) {
        let local = generateAliasAddress(options);
        if (options.format === "domain" && attempt > 0) {
            local += `${options.separator ?? "_"}${generateAliasAddress({ format: "characters", characterCount: 4 })}`;
        }
        try {
            const alias = await createAlias(env, db, caller, {
                address: `${local}@${domain}`,
                destination: key.destination,
                description: request.description.slice(0, 500),
            });
            await db
                .update(schema.apiKeys)
                .set({ lastUsedAt: new Date() })
                .where(eq(schema.apiKeys.id, key.id));
            return alias;
        } catch (error) {
            // Taken, or reserved for admins (a website named "security", say):
            // the next attempt adds random characters.
            const taken =
                error instanceof ApiException &&
                (error.code === "already_exists" || error.code === "reserved");
            // A prefix from the website may not make a valid address; go without it.
            const invalid = error instanceof ApiException && error.code === "invalid_address";
            if (invalid && options.prefixFormat !== "none") {
                options.prefixFormat = "none";
                if (options.format === "domain") options.format = "characters";
                continue;
            }
            if (!taken) throw error;
        }
    }
    throw new ApiException(409, "already_exists", "Could not find a free address; try again");
}

/** The domain asked for, else the key's, else the first the caller may use. */
async function chooseDomain(
    db: Db,
    caller: Caller,
    keyDomain: typeof schema.domains.$inferSelect | null,
    requested: string | undefined,
): Promise<string> {
    if (requested?.trim()) return requested.trim().toLowerCase();
    if (keyDomain) return keyDomain.name;
    const first = await db.query.domains.findFirst({
        ...(!isAdmin(caller) && { where: { shared: true } }),
        orderBy: { createdAt: "asc" },
    });
    if (!first) throw new ApiException(400, "unknown_domain", "No domain is available for aliases");
    return first.name;
}

async function body(c: Context): Promise<Record<string, unknown>> {
    try {
        const parsed: unknown = await c.req.json();
        return parsed && typeof parsed === "object" ? (parsed as Record<string, unknown>) : {};
    } catch {
        return {};
    }
}

const text = (value: unknown) => (typeof value === "string" ? value : "");

type CompatEnv = { Bindings: Env };

/** Errors as the service's own clients read them (Bitwarden: `error` or `message`). */
function withErrors(app: Hono<CompatEnv>, field: "error" | "message") {
    app.onError((error, c) => {
        if (error instanceof ApiException) {
            return c.json({ [field]: error.message }, error.status as ContentfulStatusCode);
        }
        console.error(error);
        return c.json({ [field]: "Internal error" }, 500);
    });
    app.notFound((c) => c.json({ [field]: "Not found" }, 404));
    return app;
}

/** addy.io: `POST /api/v1/aliases` with `{ domain, description }`. */
export const addy = withErrors(new Hono<CompatEnv>(), "message");

addy.post("/api/v1/aliases", async (c) => {
    const header = c.req.header("Authorization") ?? "";
    const db = createDb(c.env.DB);
    const auth = await authenticate(db, header.startsWith("Bearer ") ? header.slice(7).trim() : "");
    const { domain, description } = await body(c);
    const alias = await createForKey(c.env, db, auth, {
        domain: text(domain),
        description: text(description),
        hostname: hostnameIn(text(description)),
    });
    const [localPart, aliasDomain] = alias.address.split("@");
    const created = alias.createdAt.toISOString();
    return c.json(
        {
            data: {
                id: alias.id,
                email: alias.address,
                local_part: localPart,
                domain: aliasDomain,
                description: alias.description,
                active: alias.enabled,
                created_at: created,
                updated_at: created,
            },
        },
        201,
    );
});

/** SimpleLogin: `POST /api/alias/random/new?hostname=` with `{ note }`. */
export const simpleLogin = withErrors(new Hono<CompatEnv>(), "error");

simpleLogin.post("/api/alias/random/new", async (c) => {
    const db = createDb(c.env.DB);
    const auth = await authenticate(db, (c.req.header("Authentication") ?? "").trim());
    const { note } = await body(c);
    const hostname = c.req.query("hostname");
    const alias = await createForKey(c.env, db, auth, {
        description: text(note),
        hostname: hostname ? hostnameIn(hostname) : hostnameIn(text(note)),
    });
    return c.json(
        {
            id: alias.id,
            alias: alias.address,
            email: alias.address,
            note: alias.description,
            enabled: alias.enabled,
            creation_timestamp: Math.floor(alias.createdAt.getTime() / 1000),
        },
        201,
    );
});
