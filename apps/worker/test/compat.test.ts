import { env } from "cloudflare:workers";
import { describe, expect, it } from "vitest";

import { hostnameIn } from "../src/api/compat";
import { MAX_API_KEYS } from "../src/api/index";
import type * as Api from "../src/api/types";
import { api, request, signUp } from "./helpers";

const BITWARDEN_NOTE = "Website: shop.example.com. Generated by Bitwarden.";

async function setUp(domain: string, destination = "keys@inbox.test") {
    await api("POST", "/api/v1/domains", { name: domain });
    await api("POST", "/api/v1/destinations", { email: destination });
}

async function createKey(body: Partial<Api.CreateApiKey>, token?: string) {
    const response = await api<Api.NewApiKey>(
        "POST",
        "/api/v1/api-keys",
        {
            name: "Bitwarden",
            destination: "keys@inbox.test",
            domain: null,
            format: { format: "characters", characterCount: 8 },
            ...body,
        },
        token,
    );
    if (response.status !== 201) throw new Error(JSON.stringify(response.body));
    return response.body;
}

/** Bitwarden's addy.io request. */
async function addy(key: string, body: Record<string, unknown>) {
    const response = await request("POST", "/api/addy/api/v1/aliases", body, {
        headers: { Authorization: `Bearer ${key}`, Accept: "application/json" },
    });
    return { status: response.status, body: (await response.json()) as Record<string, any> };
}

/** Bitwarden's SimpleLogin request. */
async function simpleLogin(key: string, body: Record<string, unknown>, hostname?: string) {
    const query = hostname ? `?hostname=${encodeURIComponent(hostname)}` : "";
    const response = await request("POST", `/api/simplelogin/api/alias/random/new${query}`, body, {
        headers: { Authentication: key },
    });
    return { status: response.status, body: (await response.json()) as Record<string, any> };
}

async function aliasNamed(address: string) {
    const { body } = await api<Api.Alias[]>("GET", "/api/v1/aliases");
    return body.find((a) => a.address === address);
}

describe("API keys", () => {
    it("are shown once, then listed by their start only", async () => {
        await setUp("keys.test");
        const { key, apiKey } = await createKey({ domain: "keys.test" });
        expect(key).toMatch(/^mf_[\w-]{43}$/);
        expect(apiKey).toMatchObject({
            name: "Bitwarden",
            start: key.slice(0, 7),
            destination: "keys@inbox.test",
            domain: "keys.test",
            lastUsedAt: null,
        });
        const { body } = await api<Api.ApiKey[]>("GET", "/api/v1/api-keys");
        expect(body.find((k) => k.id === apiKey.id)).toEqual(apiKey);
        expect(JSON.stringify(body)).not.toContain(key);
    });

    it("can't manage keys or anything else themselves", async () => {
        await setUp("keys.test");
        const { key } = await createKey({});
        expect((await api("GET", "/api/v1/api-keys", undefined, key)).status).toBe(401);
        expect((await api("GET", "/api/v1/aliases", undefined, key)).status).toBe(401);
    });

    it("stop working once deleted, and keep their destination from being deleted", async () => {
        await setUp("gone.test", "kept@inbox.test");
        const { key, apiKey } = await createKey({ destination: "kept@inbox.test" });
        const destinations = await api<Api.Destination[]>("GET", "/api/v1/destinations");
        const kept = destinations.body.find((d) => d.email === "kept@inbox.test")!;
        expect((await api("DELETE", `/api/v1/destinations/${kept.id}`)).status).toBe(409);

        expect((await api("DELETE", `/api/v1/api-keys/${apiKey.id}`)).status).toBe(204);
        const after = await addy(key, { domain: "gone.test" });
        expect(after).toEqual({ status: 401, body: { message: "Invalid API key" } });
    });

    it("refuse the website domain format without a domain prefix", async () => {
        await setUp("keys.test");
        const response = await api<Api.ApiError>("POST", "/api/v1/api-keys", {
            name: "x",
            destination: "keys@inbox.test",
            domain: null,
            format: { format: "domain", prefixFormat: "none" },
        });
        expect(response.status).toBe(400);
        expect(response.body.error.message).toContain("prefixFormat");
    });

    it("keep to the limit, also when created at the same time", async () => {
        const token = await signUp("many-keys@user.test");
        await api("POST", "/api/v1/destinations", { email: "many-keys@user.test" }, token);
        const body = {
            name: "k",
            destination: "many-keys@user.test",
            domain: null,
            format: { format: "characters" },
        };
        for (let i = 0; i < MAX_API_KEYS - 2; i += 1) {
            expect((await api("POST", "/api/v1/api-keys", body, token)).status).toBe(201);
        }
        const racing = await Promise.all(
            Array.from({ length: 5 }, () => api("POST", "/api/v1/api-keys", body, token)),
        );
        expect(racing.filter((r) => r.status === 201)).toHaveLength(2);
        expect(racing.filter((r) => r.status === 403)).toHaveLength(3);
        const keys = await api<Api.ApiKey[]>("GET", "/api/v1/api-keys", undefined, token);
        expect(keys.body).toHaveLength(MAX_API_KEYS);
    });

    it("refuse the custom format and unknown domains", async () => {
        await setUp("keys.test");
        const custom = await api("POST", "/api/v1/api-keys", {
            name: "x",
            destination: "keys@inbox.test",
            domain: null,
            format: { format: "custom" },
        });
        expect(custom.status).toBe(400);
        const unknown = await api("POST", "/api/v1/api-keys", {
            name: "x",
            destination: "keys@inbox.test",
            domain: "nope.test",
            format: { format: "characters" },
        });
        expect(unknown.status).toBe(400);
    });
});

describe("addy.io-compatible endpoint", () => {
    it("creates an alias as Bitwarden asks for one", async () => {
        await setUp("addy.test");
        const { key, apiKey } = await createKey({});
        const { status, body } = await addy(key, {
            domain: "addy.test",
            description: BITWARDEN_NOTE,
        });
        expect(status).toBe(201);
        expect(body.data.email).toMatch(/^[a-z0-9]{8}@addy\.test$/);
        expect(body.data).toMatchObject({
            domain: "addy.test",
            active: true,
            description: BITWARDEN_NOTE,
        });

        const alias = await aliasNamed(body.data.email);
        expect(alias).toMatchObject({
            destination: "keys@inbox.test",
            description: BITWARDEN_NOTE,
        });
        const keys = await api<Api.ApiKey[]>("GET", "/api/v1/api-keys");
        expect(typeof keys.body.find((k) => k.id === apiKey.id)?.lastUsedAt).toBe("number");
    });

    it("names aliases after the website with the key's format", async () => {
        await setUp("site.test");
        const { key } = await createKey({
            format: {
                format: "words",
                wordCount: 2,
                separator: ".",
                prefixFormat: "domainWithoutExtension",
            },
        });
        const { body } = await addy(key, { domain: "site.test", description: BITWARDEN_NOTE });
        expect(body.data.email).toMatch(/^example\.[a-z]+\.[a-z]+@site\.test$/);

        const named = await createKey({
            format: { format: "domain", prefixFormat: "domainWithExtension" },
        });
        const first = await addy(named.key, { domain: "site.test", description: BITWARDEN_NOTE });
        expect(first.body.data.email).toBe("example.com@site.test");
        // Taken now: the next one gets random characters added.
        const second = await addy(named.key, { domain: "site.test", description: BITWARDEN_NOTE });
        expect(second.body.data.email).toMatch(/^example\.com_[a-z0-9]{4}@site\.test$/);
        // Without a website, random characters.
        const plain = await addy(named.key, { domain: "site.test", description: "" });
        expect(plain.body.data.email).toMatch(/^[a-z0-9]{5}@site\.test$/);
    });

    it("answers errors the way Bitwarden shows them", async () => {
        await setUp("addy.test");
        const { key } = await createKey({});
        expect(await addy("mf_wrong", { domain: "addy.test" })).toEqual({
            status: 401,
            body: { message: "Invalid API key" },
        });
        expect(await addy(key, { domain: "elsewhere.test" })).toEqual({
            status: 400,
            body: { message: "Domain elsewhere.test is not available" },
        });
    });
});

describe("SimpleLogin-compatible endpoint", () => {
    it("creates an alias on the key's domain, named after the hostname", async () => {
        await setUp("sl.test");
        const { key } = await createKey({
            domain: "sl.test",
            format: {
                format: "characters",
                characterCount: 6,
                prefixFormat: "fullDomain",
                separator: "-",
            },
        });
        const { status, body } = await simpleLogin(
            key,
            { note: BITWARDEN_NOTE },
            "login.shop.example.com",
        );
        expect(status).toBe(201);
        expect(body.alias).toMatch(/^login\.shop\.example\.com-[a-z0-9]{6}@sl\.test$/);
        expect(await aliasNamed(body.alias)).toMatchObject({ description: BITWARDEN_NOTE });
    });

    it("answers a wrong key with an error field", async () => {
        expect(await simpleLogin("nope", { note: "" })).toEqual({
            status: 401,
            body: { error: "Invalid API key" },
        });
    });

    it("lets browsers send its header (CORS)", async () => {
        const response = await request(
            "OPTIONS",
            "/api/simplelogin/api/alias/random/new",
            undefined,
            {
                headers: {
                    Origin: "https://vault.bitwarden.com",
                    "Access-Control-Request-Method": "POST",
                    "Access-Control-Request-Headers": "authentication,content-type",
                },
            },
        );
        expect(response.headers.get("Access-Control-Allow-Headers")?.toLowerCase()).toContain(
            "authentication",
        );
    });
});

describe("keys of accounts", () => {
    it("create aliases as the account, within its limits and on shared domains", async () => {
        await api("POST", "/api/v1/domains", { name: "shared-keys.test", shared: true });
        await api("POST", "/api/v1/domains", { name: "private-keys.test" });
        const token = await signUp("keyuser@user.test");
        await api("POST", "/api/v1/destinations", { email: "keyuser@user.test" }, token);
        const { key } = await createKey({ destination: "keyuser@user.test" }, token);

        // No domain asked for and none on the key: the first shared one.
        const first = await simpleLogin(key, { note: "" });
        expect(first.body.alias).toMatch(/@shared-keys\.test$/);
        const mine = await api<Api.Alias[]>("GET", "/api/v1/aliases", undefined, token);
        expect(mine.body.map((a) => a.address)).toContain(first.body.alias);

        expect((await addy(key, { domain: "private-keys.test" })).status).toBe(400);

        // MAX_ALIASES_PER_USER is 3 in the tests.
        await addy(key, { domain: "shared-keys.test" });
        await addy(key, { domain: "shared-keys.test" });
        expect(await addy(key, { domain: "shared-keys.test" })).toEqual({
            status: 403,
            body: { message: "Accounts can have up to 3 aliases" },
        });
    });

    it("can't pass the alias limit with requests at the same time", async () => {
        await api("POST", "/api/v1/domains", { name: "shared-race.test", shared: true });
        const token = await signUp("racer@user.test");
        await api("POST", "/api/v1/destinations", { email: "racer@user.test" }, token);
        const { key } = await createKey({ destination: "racer@user.test" }, token);
        const results = await Promise.all(
            Array.from({ length: 6 }, () => addy(key, { domain: "shared-race.test" })),
        );
        // MAX_ALIASES_PER_USER is 3 in the tests.
        expect(results.filter((r) => r.status === 201)).toHaveLength(3);
        const mine = await api<Api.Alias[]>("GET", "/api/v1/aliases", undefined, token);
        expect(mine.body).toHaveLength(3);
    });

    it("name an alias after a reserved website with random characters added", async () => {
        await api("POST", "/api/v1/domains", { name: "shared-reserved.test", shared: true });
        const token = await signUp("reserved-key@user.test");
        await api("POST", "/api/v1/destinations", { email: "reserved-key@user.test" }, token);
        const { key } = await createKey(
            {
                destination: "reserved-key@user.test",
                format: { format: "domain", prefixFormat: "domainWithoutExtension" },
            },
            token,
        );
        const { status, body } = await addy(key, {
            domain: "shared-reserved.test",
            description: "Website: postmaster.org. Generated by Bitwarden.",
        });
        expect(status).toBe(201);
        expect(body.data.email).toMatch(/^postmaster_[a-z0-9]{4}@shared-reserved\.test$/);
    });

    it("stop working when the account is suspended", async () => {
        await api("POST", "/api/v1/domains", { name: "shared-ban.test", shared: true });
        const token = await signUp("banned-key@user.test");
        await api("POST", "/api/v1/destinations", { email: "banned-key@user.test" }, token);
        const { key } = await createKey({ destination: "banned-key@user.test" }, token);
        const user = await env.DB.prepare("SELECT id FROM user WHERE email = ?")
            .bind("banned-key@user.test")
            .first<{ id: string }>();
        await api("PATCH", `/api/v1/users/${user!.id}`, { banned: true });
        expect((await addy(key, { domain: "shared-ban.test" })).status).toBe(403);
    });
});

describe("hostnames in Bitwarden's notes", () => {
    it("finds the website, or nothing", () => {
        expect(hostnameIn(BITWARDEN_NOTE)).toBe("shop.example.com");
        expect(hostnameIn("Webseite: beispiel.de. Generiert von Bitwarden.")).toBe("beispiel.de");
        expect(hostnameIn("Generated by Bitwarden.")).toBeUndefined();
        expect(hostnameIn("login.example.org")).toBe("login.example.org");
    });
});
